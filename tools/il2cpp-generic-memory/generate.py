# The generated files are not in Git. On a branch that has no asmdef beside them they would be compiled into the
# project's own assembly, so they hold nothing unless the build defines the symbol the scenario's asmdef asks for.
GUARD = "GENERIC_MEMORY_SCENARIO"


def write(name, text):
    with open(os.path.join(OUT, name), "w", encoding="utf-8", newline="\n") as file:
        file.write("#if %s\n%s#endif\n" % (GUARD, text))


def main():
    refs = int(sys.argv[1]) if len(sys.argv) > 1 else 200
    vals = int(sys.argv[2]) if len(sys.argv) > 2 else 40
    os.makedirs(OUT, exist_ok=True)
    for name in os.listdir(OUT):
        if name.endswith(".cs"):
            os.remove(os.path.join(OUT, name))

    data = [HEADER.replace("using GenericMemory.Data;\n", "").replace("using GenericMemory.Lib;\n", ""), "namespace GenericMemory.Data\n{\n"]
    for index in range(refs):
        data.append(
            "\tpublic sealed class E%04d : IEntity\n\t{\n\t\tpublic int Id { get; }\n\t\tpublic string Name;\n\n"
            "\t\tpublic E%04d(int id)\n\t\t{\n\t\t\tId = id;\n\t\t\tName = \"e\";\n\t\t}\n\t}\n\n" % (index, index)
        )
    for index in range(vals):
        data.append("\tpublic struct S%04d\n\t{\n\t\tpublic int Id;\n\t\tpublic float Value;\n\t}\n\n" % index)
        data.append("\tpublic enum K%04d\n\t{\n\t\tA,\n\t\tB,\n\t\tC,\n\t}\n\n" % index)
    data.append("}\n")
    write("Data.cs", "".join(data))
    write("Thin.cs", THIN)

    counts = {"ref": refs, "val": vals, "enum": vals}
    prefixes = {"ref": "E", "val": "S", "enum": "K"}
    for name, kind, body, members in PATTERNS:
        count = counts[kind]
        text = [HEADER, "namespace GenericMemory.Patterns\n{\n\tpublic static class %s\n\t{\n\t\tpublic const int Types = %d;\n\n" % (name, count)]
        text.append("\t\tpublic static void Run(int index)\n\t\t{\n\t\t\tswitch (index)\n\t\t\t{\n")
        for index in range(count):
            text.append("\t\t\t\tcase %d:\n\t\t\t\t\tM%04d();\n\t\t\t\t\tbreak;\n" % (index, index))
        text.append("\t\t\t}\n\t\t}\n\n")
        for index in range(count):
            fields = {"E": "%s%04d" % (prefixes[kind], index), "i": "%04d" % index, "n": str(index)}
            text.append("\t\tstatic void M%04d()\n\t\t{\n" % index)
            text.append("\n".join("\t" + line for line in body.format(**fields).split("\n")))
            text.append("\n\t\t}\n\n")
            if members:
                text.append("\n".join(("\t" + line) if line else line for line in members.format(**fields).split("\n")))
                text.append("\n")
        text.append("\t}\n}\n")
        write(name + ".cs", "".join(text))

    registry = [HEADER, "namespace GenericMemory.Patterns\n{\n\tpublic static class Registry\n\t{\n"]
    registry.append("\t\tpublic static readonly string[] Names = { %s };\n\n" % ", ".join('"%s"' % name for name, _, _, _ in PATTERNS))
    registry.append("\t\tpublic static int Types(string name)\n\t\t{\n\t\t\tswitch (name)\n\t\t\t{\n")
    for name, _, _, _ in PATTERNS:
        registry.append('\t\t\t\tcase "%s":\n\t\t\t\t\treturn %s.Types;\n' % (name, name))
    registry.append("\t\t\t}\n\t\t\treturn 0;\n\t\t}\n\n")
    registry.append("\t\tpublic static void Run(string name, int index)\n\t\t{\n\t\t\tswitch (name)\n\t\t\t{\n")
    for name, _, _, _ in PATTERNS:
        registry.append('\t\t\t\tcase "%s":\n\t\t\t\t\t%s.Run(index);\n\t\t\t\t\tbreak;\n' % (name, name))
    registry.append("\t\t\t}\n\t\t}\n\t}\n}\n")
    write("Registry.cs", "".join(registry))
    print("generated %d patterns over %d reference types and %d value types" % (len(PATTERNS), refs, vals))


main()
